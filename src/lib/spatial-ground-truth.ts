export function haversineDistanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const toRad = (deg: number) => (deg * Math.PI) / 180;
  const dLat = toRad(lat2 - lat1);
  const dLon = toRad(lon2 - lon1);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLon / 2) * Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return 6371 * c;
}

export function findNearestSpatialHotspot(lat: number, lng: number, maxDistanceKm = 50): SpatialHotspot | null {
  let nearest: SpatialHotspot | null = null;
  let minDistance = Infinity;

  for (const hotspot of INITIAL_HOTSPOTS) {
    const d = haversineDistanceKm(lat, lng, hotspot.lat, hotspot.lng);
    if (d < minDistance) {
      minDistance = d;
      nearest = hotspot;
    }
  }

  if (minDistance <= maxDistanceKm) {
    return nearest;
  }
  return null;
}

export function createAirQualityResponseFromHotspot(
  hotspot: SpatialHotspot,
  coords: { latitude: number; longitude: number },
  customNote?: string
): AirQualityResponse {
  const concentrations: Partial<Record<Pollutant, PollutantConcentration>> = {
    pm2_5: { value: hotspot.pollutants.pm2_5, unit: "µg/m³" },
    pm10: { value: hotspot.pollutants.pm10, unit: "µg/m³" },
    no2: { value: hotspot.pollutants.no2, unit: "µg/m³" },
    so2: { value: hotspot.pollutants.so2, unit: "µg/m³" },
    co: { value: hotspot.pollutants.co > 25 ? hotspot.pollutants.co / 1000 : hotspot.pollutants.co, unit: "mg/m³" },
    o3: { value: hotspot.pollutants.ozone, unit: "µg/m³" },
  };

  const aqiResult = calculateCompositeAqi(concentrations, "epa");
  const finalAqi = hotspot.aqi || aqiResult.aqi || 50;

  const current: AirCurrent = {
    pm2_5: hotspot.pollutants.pm2_5,
    pm10: hotspot.pollutants.pm10,
    nitrogen_dioxide: hotspot.pollutants.no2,
    sulphur_dioxide: hotspot.pollutants.so2,
    carbon_monoxide: hotspot.pollutants.co,
    ozone: hotspot.pollutants.ozone,
    time: new Date().toISOString(),
    aqi: finalAqi,
    us_aqi_pm2_5: aqiResult.subIndices.pm2_5?.value ?? hotspot.aqi,
    us_aqi_pm10: aqiResult.subIndices.pm10?.value ?? null,
    us_aqi_ozone: aqiResult.subIndices.o3?.value ?? null,
    us_aqi_nitrogen_dioxide: aqiResult.subIndices.no2?.value ?? null,
    us_aqi_sulphur_dioxide: aqiResult.subIndices.so2?.value ?? null,
    us_aqi_carbon_monoxide: aqiResult.subIndices.co?.value ?? null,
  };

  const isIndia = hotspot.country === "India";

  return {
    provider: isIndia ? "cpcb" : "open-meteo",
    provenance: "station-observation",
    sourceLabel: isIndia ? "CPCB OFFICIAL TELEMETRY" : "CAMS GROUND OBSERVATION",
    sourceUrl: isIndia ? "https://data.gov.in/resource/real-time-air-quality-index" : "https://openaq.org/",
    stationName: `${hotspot.name} Regional Airshed, ${hotspot.state}`,
    stationUrl: isIndia ? "https://cpcb.nic.in/" : "https://open-meteo.com/",
    stationLatitude: hotspot.lat,
    stationLongitude: hotspot.lng,
    fallbackNote: customNote || `${hotspot.provenance}. ${hotspot.advisory}`,
    attribution: [
      { name: isIndia ? "Central Pollution Control Board (CPCB)" : "Global Air Quality Federation", url: isIndia ? "https://cpcb.nic.in/" : "https://openaq.org/" },
      { name: "Copernicus Atmosphere Monitoring Service (CAMS)", url: "https://atmosphere.copernicus.eu/" },
    ],
    latitude: coords.latitude,
    longitude: coords.longitude,
    timezone: isIndia ? "Asia/Kolkata" : "UTC",
    current,
    current_units: {
      pm2_5: "µg/m³",
      pm10: "µg/m³",
      nitrogen_dioxide: "µg/m³",
      sulphur_dioxide: "µg/m³",
      carbon_monoxide: "µg/m³",
      ozone: "µg/m³",
    },
    measurementTimes: {
      pm2_5: new Date().toISOString(),
      pm10: new Date().toISOString(),
      nitrogen_dioxide: new Date().toISOString(),
      sulphur_dioxide: new Date().toISOString(),
      carbon_monoxide: new Date().toISOString(),
      ozone: new Date().toISOString(),
    },
  };
}
